import { useQuery } from '@tanstack/react-query';
import { AlertTriangle, ArrowLeft, Download, Link2, Lock, LockOpen, Plus, RotateCcw, Sparkles, Trash2, Undo2 } from 'lucide-react';
import { useEffect, useState } from 'react';
import { Link, useParams } from 'react-router';
import { Button, Card, cx, DemoBadge, ErrorState, fmtDate, Input, Loading, Notice, PageHeader, Pill, ScoreBar, Select, Tabs, Textarea } from '../components/ui';
import { api, download } from '../lib/api';
import { useAction } from '../lib/hooks';
import type { ResumeBullet, ResumeContent, ResumeQuality } from '../lib/types';

interface Detail {
  resume: { id: number; title: string; kind: string; template: string; language: 'en' | 'vi'; jobId: number | null };
  version: { id: number; versionNo: number; content: ResumeContent; quality: ResumeQuality; generatedBy: string | null; note: string };
  versions: { id: number; versionNo: number; note: string; createdBy: string; generatedBy: string | null; createdAt: string }[];
  job: { id: number; title: string; company: string; isDemo: boolean } | null;
  templates: { key: string; name: string; atsNote: string }[];
  evidenceSources: { items: { id: number; kind: string; title: string; organization: string }[]; skills: { id: number; name: string; status: string }[] };
}

const newId = () => `b_${Math.random().toString(36).slice(2, 10)}`;

export default function ResumeEditor() {
  const { id } = useParams();
  const q = useQuery({ queryKey: ['resume', id], queryFn: () => api.get<Detail>(`/resumes/${id}`) });
  const [content, setContent] = useState<ResumeContent | null>(null);
  const [template, setTemplate] = useState('classic');
  const [language, setLanguage] = useState<'en' | 'vi'>('en');
  const [note, setNote] = useState('');
  const [tab, setTab] = useState<'quality' | 'versions'>('quality');
  const [linking, setLinking] = useState<string | null>(null);
  useEffect(() => { if (q.data) { setContent(structuredClone(q.data.version.content)); setTemplate(q.data.resume.template); setLanguage(q.data.resume.language); } }, [q.data]);
  const inv = [['resume', id], ['resumes']];
  const save = useAction(() => api.post(`/resumes/${id}/versions`, { content, note: note || 'Edited', template, language }), inv, () => setNote(''));
  const regen = useAction(() => api.post(`/resumes/${id}/regenerate`), inv);
  const restore = useAction((vid: number) => api.post(`/resumes/${id}/versions/${vid}/restore`), inv);
  if (q.isLoading || (!content && !q.error)) return <Loading rows={5} />;
  if (q.error) return <ErrorState error={q.error} retry={q.refetch} />;
  const d = q.data!;
  const c = content!;
  const dirty = JSON.stringify(c) !== JSON.stringify(d.version.content) || template !== d.resume.template || language !== d.resume.language;
  const quality = d.version.quality;

  const update = (fn: (draft: ResumeContent) => void) => setContent((prev) => { const n = structuredClone(prev!); fn(n); return n; });
  const findBullet = (draft: ResumeContent, bid: string) => draft.sections.flatMap((s) => s.entries.flatMap((e) => e.bullets)).find((b) => b.id === bid)!;
  const linkTarget = linking ? c.sections.flatMap((s) => s.entries.flatMap((e) => e.bullets)).find((b) => b.id === linking) : null;

  return (
    <>
      <Link to="/resume" className="mb-4 inline-flex items-center gap-1 text-body-sm text-muted hover:text-ink"><ArrowLeft className="size-4" />CVs</Link>
      <PageHeader eyebrow={<span className="flex items-center gap-2">{d.resume.kind === 'tailored' ? 'Tailored CV' : 'Master CV'} · v{d.version.versionNo}{d.job && <> · for {d.job.title} — {d.job.company} {d.job.isDemo && <DemoBadge />}</>}</span>} title={d.resume.title}
        actions={<>
          <Button variant="ghost" icon={<Download className="size-4" />} disabled={dirty} title={dirty ? 'Save first' : undefined} onClick={() => download(`/resumes/${id}/export?format=pdf&versionId=${d.version.id}`, `${d.resume.title} v${d.version.versionNo}.pdf`)}>PDF</Button>
          <Button variant="ghost" icon={<Download className="size-4" />} disabled={dirty} onClick={() => download(`/resumes/${id}/export?format=docx&versionId=${d.version.id}`, `${d.resume.title} v${d.version.versionNo}.docx`)}>DOCX</Button>
          {d.resume.kind === 'tailored' && <Button variant="text" icon={<Sparkles className="size-4" />} loading={regen.isPending} onClick={() => regen.mutate(undefined)}>Regenerate (keeps locked)</Button>}
        </>} />
      {d.version.generatedBy && <p className="-mt-4 mb-4 text-caption text-muted">Generated by {d.version.generatedBy}.</p>}
      {quality.unverifiedClaims.length > 0 && <Notice tone="warn" className="mb-4"><b>{quality.unverifiedClaims.length} bullet(s) need your confirmation</b> — they contain claims not found in your evidence. Revert, edit, link evidence or confirm they’re true.</Notice>}

      <div className="grid gap-6 xl:grid-cols-[minmax(0,1fr)_minmax(0,1fr)_300px]">
        {/* ---------------- Editor ---------------- */}
        <div className="flex min-w-0 flex-col gap-4">
          <Card>
            <div className="grid gap-3 sm:grid-cols-2">
              <Input aria-label="Name" value={c.header.name} onChange={(e) => update((n) => { n.header.name = e.target.value; })} />
              <Input aria-label="Headline" value={c.header.headline} onChange={(e) => update((n) => { n.header.headline = e.target.value; })} />
              <Input aria-label="Email" value={c.header.email ?? ''} onChange={(e) => update((n) => { n.header.email = e.target.value; })} />
              <Input aria-label="Location" value={c.header.location ?? ''} onChange={(e) => update((n) => { n.header.location = e.target.value; })} />
              <Select aria-label="Template" value={template} onChange={(e) => setTemplate(e.target.value)}>{d.templates.map((t) => <option key={t.key} value={t.key}>{t.name}</option>)}</Select>
              <Select aria-label="Language" value={language} onChange={(e) => setLanguage(e.target.value as 'en' | 'vi')}><option value="en">English</option><option value="vi">Tiếng Việt</option></Select>
            </div>
          </Card>
          {c.sections.map((sec, si) => (
            <Card key={sec.id} padded={false} className={cx(sec.locked && 'border-signal-blue/50')}>
              <div className="flex items-center gap-2 border-b border-line px-4 py-2.5">
                <Input aria-label="Section title" value={sec.title} onChange={(e) => update((n) => { n.sections[si].title = e.target.value; })} className="border-0 px-0 font-semibold" />
                <button aria-label={sec.locked ? 'Unlock section' : 'Lock section'} title="Locked sections are kept verbatim when regenerating" onClick={() => update((n) => { n.sections[si].locked = !n.sections[si].locked; })} className={cx('rounded-md p-1.5', sec.locked ? 'text-signal-blue' : 'text-faint hover:text-ink')}>{sec.locked ? <Lock className="size-4" /> : <LockOpen className="size-4" />}</button>
              </div>
              {sec.entries.map((en, ei) => (
                <div key={en.id} className="border-b border-line px-4 py-3 last:border-0">
                  {en.heading !== undefined && <div className="mb-2 text-body-sm font-medium">{en.heading}{en.subheading && <span className="font-normal text-ink-2"> · {en.subheading}</span>}<span className="ml-2 text-caption text-muted">{en.period}</span></div>}
                  <div className="flex flex-col gap-2">
                    {en.bullets.map((b, bi) => (
                      <BulletEditor key={b.id} b={b}
                        onText={(t) => update((n) => { n.sections[si].entries[ei].bullets[bi].text = t; })}
                        onLock={() => update((n) => { const x = n.sections[si].entries[ei].bullets[bi]; x.locked = !x.locked; })}
                        onRevert={() => update((n) => { const x = n.sections[si].entries[ei].bullets[bi]; x.text = x.originalText ?? x.text; })}
                        onConfirm={() => update((n) => { const x = findBullet(n, b.id); x.userConfirmed = !x.userConfirmed; })}
                        onLink={() => setLinking(b.id)}
                        onDelete={() => update((n) => { n.sections[si].entries[ei].bullets.splice(bi, 1); })} />
                    ))}
                    <button onClick={() => update((n) => { n.sections[si].entries[ei].bullets.push({ id: newId(), text: '', evidence: en.profileItemId ? [{ type: 'profile_item', id: en.profileItemId }] : [] }); })} className="inline-flex items-center gap-1 self-start text-caption text-primary"><Plus className="size-3" />Add bullet</button>
                  </div>
                </div>
              ))}
            </Card>
          ))}
          <div className="sticky bottom-4 flex items-center gap-2 rounded-lg border border-line bg-surface px-4 py-3 shadow-mockup">
            <Input aria-label="Version note" placeholder="Version note (optional)" value={note} onChange={(e) => setNote(e.target.value)} />
            <Button variant="primary" disabled={!dirty} loading={save.isPending} onClick={() => save.mutate(undefined)}>Save as v{d.versions[0].versionNo + 1}</Button>
          </div>
          {save.error && <p className="text-body-sm text-vermillion">{(save.error as Error).message}</p>}
        </div>

        {/* ---------------- Preview ---------------- */}
        <div className="min-w-0"><div className="sticky top-20"><Preview content={c} template={template} /></div></div>

        {/* ---------------- Quality & versions ---------------- */}
        <div className="flex flex-col gap-4">
          <Tabs value={tab} onChange={setTab} items={[{ value: 'quality', label: 'Quality' }, { value: 'versions', label: `Versions (${d.versions.length})` }]} />
          {tab === 'quality' ? (
            <Card className="flex flex-col gap-4 text-body-sm">
              {dirty && <Notice tone="warn">Analysis reflects the last saved version.</Notice>}
              {[
                ['JD relevance', quality.jdRelevance.score],
                ['Evidence coverage', quality.evidenceCoverage.score],
                ['Clarity', quality.clarity.score],
                ['Completeness', quality.completeness.score],
                ['Format compatibility', quality.formatCompatibility.score],
              ].map(([l, v]) => <div key={l as string}><div className="flex justify-between"><span>{l}</span><span className="text-muted">{v ?? '—'}{v != null && '%'}</span></div><ScoreBar value={v as number | null} className="mt-1" tone={(v as number) >= 75 ? 'green' : (v as number) >= 50 ? 'blue' : 'yellow'} /></div>)}
              {quality.jdRelevance.missing.length > 0 && <div><div className="font-medium">JD skills not in this CV</div><div className="mt-1 flex flex-wrap gap-1">{quality.jdRelevance.missing.map((m) => <Pill key={m}>{m}</Pill>)}</div><p className="mt-1 text-caption text-muted">{quality.jdRelevance.note}</p></div>}
              {quality.clarity.issues.length > 0 && <div><div className="font-medium">Clarity</div><ul className="mt-1 flex flex-col gap-1 text-caption text-ink-2">{quality.clarity.issues.map((i) => <li key={i}>{i}</li>)}</ul></div>}
              {quality.completeness.missingSections.length > 0 && <div className="text-caption">Missing: {quality.completeness.missingSections.join(', ')}</div>}
              <ul className="text-caption text-muted">{quality.formatCompatibility.notes.map((n) => <li key={n}>{n}</li>)}</ul>
              <p className="text-caption text-muted">{quality.disclaimer}</p>
            </Card>
          ) : (
            <Card padded={false}>
              {d.versions.map((v) => (
                <div key={v.id} className="flex items-start gap-2 border-b border-line px-4 py-3 last:border-0">
                  <div className="flex-1"><div className="text-body-sm font-medium">v{v.versionNo} {v.id === d.version.id && <Pill tone="green">current</Pill>}</div><div className="text-caption text-muted">{v.note} · {v.createdBy} · {fmtDate(v.createdAt)}</div></div>
                  {v.id !== d.version.id && <button aria-label={`Restore version ${v.versionNo}`} onClick={() => restore.mutate(v.id)} className="rounded-md p-1 text-muted hover:text-primary"><RotateCcw className="size-4" /></button>}
                </div>
              ))}
            </Card>
          )}
        </div>
      </div>

      {linkTarget && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/30 p-4" onMouseDown={() => setLinking(null)}>
          <Card className="max-h-[80vh] w-full max-w-md overflow-auto shadow-mockup" onMouseDown={(e) => e.stopPropagation()}>
            <div className="mb-3 font-semibold">Link evidence</div>
            <p className="mb-3 text-caption text-muted">Choose the profile entries or skills that support: “{linkTarget.text.slice(0, 80)}”</p>
            {d.evidenceSources.items.map((it) => {
              const on = linkTarget.evidence.some((e) => e.type === 'profile_item' && e.id === it.id);
              return <label key={it.id} className="flex items-center gap-2 py-1 text-body-sm"><input type="checkbox" checked={on} onChange={() => update((n) => { const b = findBullet(n, linkTarget.id); b.evidence = on ? b.evidence.filter((e) => !(e.type === 'profile_item' && e.id === it.id)) : [...b.evidence, { type: 'profile_item', id: it.id }]; })} />{it.title}<span className="text-caption text-muted">{it.organization} · {it.kind}</span></label>;
            })}
            <div className="mt-3 flex justify-end"><Button variant="primary" onClick={() => setLinking(null)}>Done</Button></div>
          </Card>
        </div>
      )}
    </>
  );
}

function BulletEditor({ b, onText, onLock, onRevert, onConfirm, onLink, onDelete }: { b: ResumeBullet; onText: (t: string) => void; onLock: () => void; onRevert: () => void; onConfirm: () => void; onLink: () => void; onDelete: () => void }) {
  const flagged = b.status === 'needs_confirmation' && !b.userConfirmed;
  return (
    <div className={cx('rounded-md border p-2', flagged ? 'border-marigold bg-marigold/5' : 'border-transparent')}>
      <Textarea rows={2} value={b.text} onChange={(e) => onText(e.target.value)} className="min-h-0 border-0 bg-transparent px-1 py-1" aria-label="Bullet text" />
      {b.issues && b.issues.length > 0 && <ul className="mt-1 flex flex-col gap-0.5 px-1">{b.issues.map((i) => <li key={i} className="flex items-start gap-1 text-caption text-[#7a4f00] dark:text-marigold"><AlertTriangle className="mt-0.5 size-3 shrink-0" />{i}</li>)}</ul>}
      <div className="mt-1 flex flex-wrap items-center gap-1 px-1 text-caption text-muted">
        <span className="mr-auto">{b.evidence.length ? `${b.evidence.length} evidence link(s)` : 'no evidence'}</span>
        {b.originalText && b.originalText !== b.text && <button onClick={onRevert} className="inline-flex items-center gap-1 rounded px-1.5 py-0.5 hover:bg-black/5 dark:hover:bg-white/5" title={`Original: ${b.originalText}`}><Undo2 className="size-3" />Revert to source</button>}
        <button onClick={onLink} className="inline-flex items-center gap-1 rounded px-1.5 py-0.5 hover:bg-black/5 dark:hover:bg-white/5"><Link2 className="size-3" />Evidence</button>
        {(b.status === 'needs_confirmation' || b.userConfirmed) && <label className="inline-flex items-center gap-1 px-1.5"><input type="checkbox" checked={!!b.userConfirmed} onChange={onConfirm} />I confirm this is true</label>}
        <button onClick={onLock} aria-label={b.locked ? 'Unlock bullet' : 'Lock bullet'} className={cx('rounded p-1', b.locked ? 'text-signal-blue' : 'hover:text-ink')}>{b.locked ? <Lock className="size-3" /> : <LockOpen className="size-3" />}</button>
        <button onClick={onDelete} aria-label="Delete bullet" className="rounded p-1 hover:text-vermillion"><Trash2 className="size-3" /></button>
      </div>
    </div>
  );
}

function Preview({ content, template }: { content: ResumeContent; template: string }) {
  const modern = template === 'modern';
  const compact = template === 'compact';
  const side = modern ? content.sections.filter((s) => s.type === 'skills' || s.type === 'certifications' || s.type === 'education') : [];
  const main = content.sections.filter((s) => !side.includes(s));
  const Sec = ({ s }: { s: ResumeContent['sections'][number] }) => (
    <div className={compact ? 'mb-3' : 'mb-5'}>
      <div className="mb-1.5 border-b border-[#ddd] pb-0.5 text-[10px] font-bold tracking-[0.08em] text-[#0075de] uppercase">{s.title}</div>
      {s.entries.map((e) => (
        <div key={e.id} className="mb-2">
          {e.heading && <div className="flex justify-between gap-2 text-[11px]"><span className="font-semibold">{e.heading}{e.subheading && <span className="font-normal"> — {e.subheading}</span>}</span><span className="shrink-0 text-[#777]">{e.period}</span></div>}
          {s.type === 'summary' || s.type === 'skills' ? e.bullets.map((b) => <p key={b.id} className="text-[10.5px] leading-snug">{b.text}</p>) : <ul className="list-disc pl-4">{e.bullets.map((b) => <li key={b.id} className={cx('text-[10.5px] leading-snug', b.status === 'needs_confirmation' && !b.userConfirmed && 'bg-[#ffb11033]')}>{b.text}</li>)}</ul>}
        </div>
      ))}
    </div>
  );
  return (
    <div className="aspect-[1/1.414] overflow-auto rounded-sm bg-white p-7 text-[#222] shadow-mockup" aria-label="CV preview">
      <div className={compact ? 'mb-3' : 'mb-5'}><div className="text-[20px] font-bold tracking-tight text-[#111]">{content.header.name}</div><div className="text-[11px] text-[#555]">{content.header.headline}</div><div className="text-[10px] text-[#777]">{[content.header.email, content.header.location].filter(Boolean).join(' · ')}</div></div>
      {modern ? <div className="grid grid-cols-[1fr_34%] gap-5"><div>{main.map((s) => <Sec key={s.id} s={s} />)}</div><div className="border-l border-[#eee] pl-4">{side.map((s) => <Sec key={s.id} s={s} />)}</div></div> : content.sections.map((s) => <Sec key={s.id} s={s} />)}
    </div>
  );
}
